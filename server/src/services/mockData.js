/** 全量 Mock 题库（剔除筛选元数据，仅含 §4 Question 结构，严格符合 Schema） */
export const mockQuestions = _bank.map((entry) => ({ ...entry.question }));

/**
 * 带筛选元数据的只读题库（供题库检索服务 questionBank 读取 module/difficulty 过滤，Wave 9）。
 * 元素 = { module, difficulty, question(§4 Question) }，与 _bank 同构；
 * 调用方不得改元数据（仅读），下发接口仍走 mockQuestions/getMockQuestions（无元数据）。
 */
export const mockBank = _bank.map((entry) => ({
  module: entry.module,
  difficulty: entry.difficulty,
  question: { ...entry.question, options: { ...entry.question.options } },
}));

/**
 * Fisher-Yates 洗牌(就地)。
 * Wave 10：Mock 兜底必须"看起来是每次新生成的题目"——同一参数不再固定返回同一批题。
 * 仅在副本上调用,不污染 _bank / mockQuestions / mockBank 常量。
 */
function _fyShuffle(arr) {
  for (let i = arr.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

/**
 * 选项乱序(仅 Mock 呈现用,真实 LLM 链路不动)：A/B/C/D 四键重排,同步 answer 键,
 * 并把解析中的首处"故选 X"声明同步为新的答案键(题库解析统一为"故选 X"格式,Wave 10 已核 16 处)。
 * 返回新对象,不改入参;结果仍严格符合 §4 Question 结构。
 * @param {object} q 符合 §4 Question
 * @returns {object} 新 Question(选项乱序、answer/解析声明同步)
 */
export function shuffleOptions(q) {
  const entries = Object.entries(q.options); // [['A',v1],['B',v2],['C',v3],['D',v4]]
  _fyShuffle(entries);
  const KEYS = ['A', 'B', 'C', 'D'];
  const options = {};
  let answer = '';
  for (let i = 0; i < entries.length; i += 1) {
    const [oldKey, value] = entries[i];
    const newKey = KEYS[i];
    options[newKey] = value;
    if (oldKey === q.answer) answer = newKey;
  }
  let analysis = typeof q.analysis === 'string' ? q.analysis : '';
  if (answer) {
    analysis = analysis.replace(/故选\s*[A-D]/, `故选 ${answer}`);
  }
  return { ...q, options, answer, analysis };
}

/**
 * 取一组 Mock 题(随机抽样：先按 module/difficulty 过滤,再洗牌后取前 count 道)
 * @param {{module?:string, difficulty?:string, count?:number}} [filters]
 *    module：命中 MOCK_MODULES 才过滤；difficulty：命中 DIFFICULTIES 才过滤；
 *    count：截断返回前 count 道（缺省返回全部）。
 * Wave 10：同一参数每次调用返回的题目子集/顺序随机,不再固定(Wave 4 回归要求"无重复题干"场景
 * 由路由层 B2 排除集硬去重兜底,不受洗牌影响)。
 * @returns {object[]} Question[]（符合 docs/DATA_SCHEMA.md §4）
 */
export function getMockQuestions(filters = {}) {
  const { module, difficulty, count } = filters || {};
  let pool = _bank.slice();

  if (module && MOCK_MODULES.includes(module)) {
    pool = pool.filter((entry) => entry.module === module);
  }
  if (difficulty && DIFFICULTIES.includes(difficulty)) {
    pool = pool.filter((entry) => entry.difficulty === difficulty);
  }

  const list = _fyShuffle(pool).map((entry) => ({ ...entry.question }));
  return typeof count === 'number' && Number.isInteger(count) ? list.slice(0, count) : list;
}

